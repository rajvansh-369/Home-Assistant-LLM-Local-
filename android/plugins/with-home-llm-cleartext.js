// Expo config plugin: plain HTTP only to the home LLM (plan §7 "Cleartext only for the home LLM").
//
// - Release (main source set): cleartext off everywhere except HOME_LLM_HOST.
// - Debug overlay: cleartext on, so Metro and a local dev API keep working.
// - <application android:networkSecurityConfig="@xml/network_security_config">.
//
// Usage in app.config.ts: ['./plugins/with-home-llm-cleartext.js', { host: HOME_LLM_HOST }]
const fs = require('fs');
const path = require('path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const NAME = 'network_security_config';
const TAG = '[with-home-llm-cleartext]';

/** A bare host name or IPv4 address: what <domain> matches (no scheme, port or path). */
const BARE_HOST = /^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)*$/i;

function releaseConfig(host) {
  const domain = host
    ? `
  <domain-config cleartextTrafficPermitted="true">
    <domain includeSubdomains="false">${host}</domain>
  </domain-config>`
    : '';
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-home-llm-cleartext.js: plain HTTP only to HOME_LLM_HOST. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="false" />${domain}
</network-security-config>
`;
}

const debugConfig = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-home-llm-cleartext.js: debug builds allow plain HTTP (Metro). -->
<network-security-config>
  <base-config cleartextTrafficPermitted="true" />
</network-security-config>
`;

function writeFile(file, contents) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, contents);
}

module.exports = function withHomeLlmCleartext(config, props = {}) {
  const host = (props.host || '').trim();
  if (host && !BARE_HOST.test(host)) {
    throw new Error(
      `${TAG} HOME_LLM_HOST must be a bare host such as 192.168.1.20, not "${host}".`,
    );
  }
  if (!host) {
    console.warn(`${TAG} HOME_LLM_HOST is empty: release builds will refuse all plain HTTP.`);
  }

  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      const src = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src');
      writeFile(path.join(src, 'main', 'res', 'xml', `${NAME}.xml`), releaseConfig(host));
      writeFile(path.join(src, 'debug', 'res', 'xml', `${NAME}.xml`), debugConfig);
      return cfg;
    },
  ]);

  return withAndroidManifest(config, (cfg) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    application.$['android:networkSecurityConfig'] = `@xml/${NAME}`;
    return cfg;
  });
};
